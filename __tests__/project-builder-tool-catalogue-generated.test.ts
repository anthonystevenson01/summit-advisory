/**
 * The generated catalogue module and the read API over it.
 *
 * The first test is the gate that stops a catalogue edit merging without a
 * rebuild: it runs the build over docs/catalogue in memory and holds the
 * committed module to the result, byte for byte. Nothing here writes a file,
 * reads env or touches the network.
 *
 * Exact values are asserted on the two fixtures only. The real categories
 * are held to rules that stay true through any correct catalogue edit: a
 * mark, a new requirement, a new product, a published flag, a new category.
 */
import { describe, test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";

import { TOOL_CATEGORIES } from "../app/lib/project-builder/tool-catalogue.generated.ts";
import {
  allCategoriesIncludingUnpublished,
  baselineRequirementsOf,
  createCatalogueReader,
  getCategory,
  groupsOf,
  productMark,
  productsOf,
  publishedCategories,
  requirementsOf,
  screenPatternsOf,
} from "../app/lib/project-builder/tool-catalogue-read.ts";
import { computeTotals, parseCategory, type ToolCategory } from "../app/lib/project-builder/tool-catalogue.ts";
import { buildCatalogue, describeFailures, renderGeneratedModule, summaryLine, type CatalogueSourceFile } from "../scripts/catalogue/build.ts";

const read = (relative: string): string => readFileSync(new URL(relative, import.meta.url), "utf8");

const CATALOGUE_FILES: CatalogueSourceFile[] = readdirSync(new URL("../docs/catalogue/", import.meta.url))
  .filter((name) => name.endsWith(".md"))
  .sort()
  .map((name) => ({ name, text: read(`../docs/catalogue/${name}`) }));
const GENERATED = read("../app/lib/project-builder/tool-catalogue.generated.ts");
const TINY = read("./fixtures/catalogue/tiny.md");
const UNMARKED = read("./fixtures/catalogue/tiny-unmarked.md");

function fixture(text: string): ToolCategory {
  const result = parseCategory(text);
  if (!result.ok) throw new Error("the fixture must parse");
  return structuredClone(result.category);
}

const tiny = (): ToolCategory => fixture(TINY);
const unmarked = (): ToolCategory => fixture(UNMARKED);

/** The module the build would write for the two fixtures alone. */
const FIXTURE_MODULE = renderGeneratedModule([tiny(), unmarked()], ["tiny.md", "tiny-unmarked.md"]);

describe("the generated module is in step with docs/catalogue", () => {
  test("every category file builds, and the committed module is exactly what the build writes", () => {
    const names = CATALOGUE_FILES.map((file) => file.name);
    assert.ok(names.includes("ordering.md") && names.includes("sales.md"), "the two first categories are in docs/catalogue");
    const result = buildCatalogue(CATALOGUE_FILES);
    if (!result.ok) assert.fail(`docs/catalogue has problems:\n${describeFailures(result.failures).join("\n")}`);
    assert.equal(GENERATED, result.moduleText, "docs/catalogue changed without a rebuild: run npm run catalogue:build");
    assert.deepEqual(TOOL_CATEGORIES, result.categories);
  });

  test("the module says it is generated and from what, and holds no date", () => {
    const [open, line, warning] = GENERATED.split("\n");
    assert.equal(open, "/**");
    assert.ok(line.startsWith(" * Generated by scripts/catalogue-build.ts from "));
    for (const file of CATALOGUE_FILES) assert.ok(line.includes(`docs/catalogue/${file.name}`), file.name);
    assert.ok(warning.startsWith(" * Do not edit."));
    assert.equal(
      renderGeneratedModule([], ["sales.md", "ordering.md"]).split("\n")[1],
      " * Generated by scripts/catalogue-build.ts from docs/catalogue/ordering.md and docs/catalogue/sales.md.",
    );
    assert.ok(GENERATED.includes("npm run catalogue:build"));
    assert.ok(GENERATED.endsWith("];\n"));
    assert.ok(FIXTURE_MODULE.startsWith("/**\n * Generated by scripts/catalogue-build.ts from docs/catalogue/tiny-unmarked.md and docs/catalogue/tiny.md.\n * Do not edit."));
    assert.equal(/\b(19|20)\d{2}\b/.test(FIXTURE_MODULE), false, "the renderer adds no date: the fixtures hold no year and neither does their module");
  });

  test("rendering is the same every time, whatever order the input comes in", () => {
    const result = buildCatalogue(CATALOGUE_FILES);
    assert.ok(result.ok);
    if (!result.ok) return;
    const names = CATALOGUE_FILES.map((file) => file.name);
    const once = renderGeneratedModule(result.categories, names);
    assert.equal(renderGeneratedModule(result.categories, names), once);
    assert.equal(renderGeneratedModule([...result.categories].reverse(), [...names].reverse()), once);
    assert.equal(once, GENERATED);
    const reversed = buildCatalogue([...CATALOGUE_FILES].reverse());
    assert.ok(reversed.ok);
    if (reversed.ok) assert.equal(reversed.moduleText, GENERATED);
  });

  test("one row of a table is one line of the module", () => {
    const lines = FIXTURE_MODULE.split("\n");
    for (const line of [
      '          { id: "A2", text: "Custom fields on a record, with types and pick lists.", baseline: false, size: "M", key: "contacts" },',
      '      { name: "Customer record", ids: ["A1", "A2"] },',
      '      { name: "Borealis Suite", tier: "Team", specification: "Documentation only", leaving: "Slow support; single sign-on missing." },',
      '      products: ["Acme Desk", "Borealis Suite"],',
      '        { id: "A3", marks: ["N", "P"] },',
      '      { id: "A3", product: "all", text: "Neither product shows a preview before commit." },',
      '      { id: "B2", product: "Borealis Suite", text: "No single sign-on in any tier." },',
      '      { title: "Acme tiers", paragraphs: ["Standard: records, fields and tasks. Plus: single sign-on and audit."] },',
      '    pendingProducts: ["Cobalt Flow", "Delta Works (orders, stock and returns)"],',
      "    pendingProducts: [],",
      "    coverage: null,",
      "    sources: null,",
      '    keys: ["contacts", "tasks"],',
    ]) {
      assert.ok(lines.includes(line), line);
    }
    assert.ok(FIXTURE_MODULE.indexOf('type: "tiny"') < FIXTURE_MODULE.indexOf('type: "tiny-unmarked"'), "categories come in type order");
  });

  test("the build refuses a file with a validator problem, a file that does not parse and a file that is not canonical", () => {
    const sound = { name: "tiny.md", text: TINY };
    assert.equal(buildCatalogue([sound]).ok, true);

    const problem = buildCatalogue([sound, { name: "other.md", text: TINY }]);
    assert.equal(problem.ok, false);
    if (!problem.ok) {
      assert.deepEqual(problem.failures.map((failure) => failure.file), ["other.md"]);
      assert.deepEqual(problem.failures[0].problems.map((p) => p.code), ["type-file-mismatch"]);
      assert.ok(describeFailures(problem.failures)[0].startsWith("other.md: [type-file-mismatch] header:"));
    }

    const unreadable = buildCatalogue([{ name: "tiny.md", text: TINY.replace("## Screen patterns", "## Screens") }]);
    assert.equal(unreadable.ok, false);
    if (!unreadable.ok) {
      assert.equal(unreadable.failures[0].errors[0].code, "unknown-section");
      assert.ok(/^tiny\.md: \[unknown-section\] line \d+:/.test(describeFailures(unreadable.failures)[0]));
    }

    const drifted = buildCatalogue([{ name: "tiny.md", text: TINY.replace("Only where a mark needs qualifying.", "Where a mark needs a word.") }]);
    assert.equal(drifted.ok, false);
    if (!drifted.ok) {
      assert.deepEqual(drifted.failures[0].problems, []);
      assert.equal(drifted.failures[0].difference?.expected, "Only where a mark needs qualifying.");
      assert.ok(describeFailures(drifted.failures)[0].startsWith("tiny.md: [not-canonical] line "));
    }

    const stale = buildCatalogue([{ name: "tiny.md", text: TINY.replace("2 baseline.", "3 baseline.") }]);
    assert.equal(stale.ok, false);
    if (!stale.ok) assert.ok(stale.failures[0].problems.some((p) => p.code === "totals-mismatch"));
  });
});

describe("the build's summary line", () => {
  test("counts in plain English, singular and plural", () => {
    const category = tiny();
    assert.equal(summaryLine("tiny", computeTotals(category), 2, 0, true), "tiny: 5 requirements in 2 groups, 2 baseline, 2 products marked, 0 still to mark, published.");
    assert.equal(summaryLine("tiny", computeTotals(category), 1, 3, false), "tiny: 5 requirements in 2 groups, 2 baseline, 1 product marked, 3 still to mark, not published.");
    category.groups = [{ name: "Alpha records", requirements: [category.groups[0].requirements[0]] }];
    assert.equal(summaryLine("tiny", computeTotals(category), 0, 0, false), "tiny: 1 requirement in 1 group, 1 baseline, 0 products marked, 0 still to mark, not published.");
  });
});

describe("nothing under app/ reads docs/ at request time", () => {
  test("the three app modules import only each other and the capability list, and no Node built in", () => {
    const allowed: Record<string, string[]> = {
      "tool-catalogue.ts": ["./catalogue.ts"],
      "tool-catalogue.generated.ts": ["./tool-catalogue.ts"],
      "tool-catalogue-read.ts": ["./tool-catalogue.generated.ts", "./tool-catalogue.ts"],
    };
    for (const [file, expected] of Object.entries(allowed)) {
      const source = read(`../app/lib/project-builder/${file}`);
      const specifiers = [...source.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+["']([^"']+)["']/gm)].map((match) => match[1]);
      const bare = [...source.matchAll(/^\s*import\s+["']([^"']+)["']/gm)].map((match) => match[1]);
      assert.deepEqual([...new Set([...specifiers, ...bare])].sort(), [...expected].sort(), file);
      assert.equal(/\brequire\s*\(|\bimport\s*\(|node:|readFileSync|docs\/catalogue/.test(source.replace(/^\s*\*.*$|^\s*\/\*\*.*$/gm, "")), false, file);
    }
  });
});

describe("the read API over the generated data", () => {
  test("the first door gives a category only when its file says published: true", () => {
    const all = allCategoriesIncludingUnpublished();
    assert.deepEqual(
      publishedCategories(),
      all.filter((c) => c.published),
    );
    for (const candidate of all) {
      const flag = /^published: (true|false)$/m.exec(read(`../docs/catalogue/${candidate.type}.md`))?.[1];
      assert.equal(candidate.published, flag === "true", candidate.type);
      assert.equal(getCategory(candidate.type), flag === "true" ? candidate : null, candidate.type);
      if (flag !== "true") assert.ok(!publishedCategories().includes(candidate), candidate.type);
    }
    assert.equal(getCategory("nonsense"), null);
    assert.equal(getCategory(""), null);
  });

  test("the named door reaches every category, in type order", () => {
    const types = allCategoriesIncludingUnpublished().map((c) => c.type);
    assert.deepEqual(types, CATALOGUE_FILES.map((file) => file.name.replace(/\.md$/, "")).sort());
    assert.ok(types.indexOf("ordering") >= 0 && types.indexOf("ordering") < types.indexOf("sales"));
  });

  test("requirements, baseline requirements, groups, screen patterns and products of the fixture", () => {
    const category = tiny();
    assert.deepEqual(requirementsOf(category), [
      { id: "A1", text: "One record per customer, with notes in one place.", baseline: true, size: "S", key: "contacts", group: "Alpha records" },
      { id: "A2", text: "Custom fields on a record, with types and pick lists.", baseline: false, size: "M", key: "contacts", group: "Alpha records" },
      { id: "A3", text: "Import from a spreadsheet with a preview before commit.", baseline: false, size: "L", key: "contacts", group: "Alpha records" },
      { id: "B1", text: "Tasks with due dates and owners, linked to a record.", baseline: true, size: "M", key: "tasks", group: "Beta work" },
      { id: "B2", text: "Single sign-on for every user.", baseline: false, size: "M", key: "none", group: "Beta work" },
    ]);
    assert.deepEqual(
      baselineRequirementsOf(category).map((r) => [r.id, r.group]),
      [
        ["A1", "Alpha records"],
        ["B1", "Beta work"],
      ],
    );
    assert.deepEqual(
      groupsOf(category).map((group) => group.name),
      ["Alpha records", "Beta work"],
    );
    assert.deepEqual(screenPatternsOf(category), [
      { name: "Customer record", ids: ["A1", "A2"] },
      { name: "Task list", ids: ["B1"] },
    ]);
    assert.deepEqual(
      productsOf(category).map((p) => [p.name, p.tier]),
      [
        ["Acme Desk", "Standard"],
        ["Borealis Suite", "Team"],
      ],
    );

    const none = unmarked();
    assert.equal(requirementsOf(none).length, 5);
    assert.deepEqual(
      baselineRequirementsOf(none).map((r) => r.id),
      ["A1", "A2", "B1"],
    );
    assert.deepEqual(productsOf(none), [], "names still to mark are not products yet");
  });

  test("the same views hold their rules over every real category", () => {
    const all = allCategoriesIncludingUnpublished();
    assert.ok(all.length >= 2);
    for (const category of all) {
      const requirements = requirementsOf(category);
      assert.equal(requirements.length, category.groups.reduce((n, group) => n + group.requirements.length, 0), category.type);
      let index = 0;
      for (const group of category.groups) {
        for (const requirement of group.requirements) {
          assert.deepEqual(requirements[index], { ...requirement, group: group.name }, `${category.type} ${requirement.id}`);
          index += 1;
        }
      }
      assert.deepEqual(
        baselineRequirementsOf(category),
        requirements.filter((r) => r.baseline),
        category.type,
      );
      assert.equal(groupsOf(category), category.groups, category.type);
      assert.equal(screenPatternsOf(category), category.patterns, category.type);
      assert.deepEqual(
        productsOf(category).map((p) => p.name),
        category.coverage?.products ?? [],
        category.type,
      );
    }
  });

  test("a product's mark, comment and evidence for a requirement of the fixture", () => {
    const category = tiny();
    assert.deepEqual(productMark(category, "Acme Desk", "A3"), {
      mark: "N",
      comment: "Neither product shows a preview before commit.",
      evidence: "No import endpoint; the documentation offers a paid service.",
    });
    assert.deepEqual(productMark(category, "Borealis Suite", "A3"), { mark: "P", comment: "Neither product shows a preview before commit.", evidence: null });
    assert.deepEqual(productMark(category, "Borealis Suite", "A2"), { mark: "P", comment: "Pick lists need the higher tier.", evidence: null });
    assert.deepEqual(productMark(category, "Acme Desk", "A2"), { mark: "F", comment: null, evidence: "Field definitions endpoint with types." });
    assert.deepEqual(productMark(category, "Acme Desk", "B2"), { mark: "P", comment: null, evidence: null });
    assert.deepEqual(productMark(category, "Borealis Suite", "B2"), { mark: "N", comment: null, evidence: "No single sign-on in any tier." });

    category.comments.push({ id: "A3", product: "Borealis Suite", text: "A preview is planned." });
    assert.equal(productMark(category, "Borealis Suite", "A3")?.comment, "A preview is planned.", "a product's own comment comes before the one for all");
    assert.equal(productMark(category, "Acme Desk", "A3")?.comment, "Neither product shows a preview before commit.");
  });

  test("an unknown product or id, a near miss on the name, and a category with no marks give null", () => {
    const category = tiny();
    assert.equal(productMark(category, "Nobody", "A1"), null);
    assert.equal(productMark(category, "acme desk", "A1"), null);
    assert.equal(productMark(category, "Acme", "A1"), null);
    assert.equal(productMark(category, "Acme Desk", "Z9"), null);
    assert.equal(productMark(category, "Acme Desk", "a1"), null);
    assert.equal(productMark(category, "all", "A3"), null);

    const none = unmarked();
    assert.equal(productMark(none, "Cobalt Flow", "A1"), null);
    assert.equal(productMark(none, "Delta Works (orders, stock and returns)", "A1"), null);
  });

  test("over every real category, every product's mark is its coverage cell, and the comment and evidence are the rows that name it", () => {
    for (const category of allCategoriesIncludingUnpublished()) {
      const coverage = category.coverage;
      if (!coverage) {
        for (const name of category.pendingProducts) assert.equal(productMark(category, name, category.groups[0].requirements[0].id), null, category.type);
        continue;
      }
      coverage.products.forEach((product, column) => {
        for (const row of coverage.rows) {
          const found = productMark(category, product, row.id);
          const at = `${category.type} ${product} ${row.id}`;
          assert.ok(found, at);
          assert.equal(found.mark, row.marks[column], at);
          const own = category.comments.find((c) => c.id === row.id && c.product === product);
          const shared = category.comments.find((c) => c.id === row.id && c.product === "all");
          assert.equal(found.comment, own?.text ?? shared?.text ?? null, at);
          assert.equal(found.evidence, category.evidence.find((e) => e.id === row.id && e.product === product)?.text ?? null, at);
        }
        assert.equal(productMark(category, product, "Z0"), null);
      });
      assert.equal(productMark(category, "A product not in the file", coverage.rows[0].id), null);
    }
  });
});

describe("createCatalogueReader", () => {
  test("an unpublished category is reachable only through the named door", () => {
    const published = tiny();
    const draft = tiny();
    draft.type = "draft";
    draft.published = false;
    const reader = createCatalogueReader([published, draft, unmarked()]);
    assert.deepEqual(reader.publishedCategories(), [published]);
    assert.deepEqual(reader.getCategory("tiny"), published);
    assert.equal(reader.getCategory("tiny"), reader.publishedCategories()[0]);
    assert.equal(reader.getCategory("draft"), null);
    assert.equal(reader.getCategory("tiny-unmarked"), null);
    assert.deepEqual(
      reader.allCategoriesIncludingUnpublished().map((c) => c.type),
      ["draft", "tiny", "tiny-unmarked"],
    );
    assert.deepEqual(productMark(published, "Borealis Suite", "A3"), { mark: "P", comment: "Neither product shows a preview before commit.", evidence: null });
    assert.deepEqual(productMark(published, "Borealis Suite", "A2"), { mark: "P", comment: "Pick lists need the higher tier.", evidence: null });
  });

  test("what a reader hands out is frozen all the way down, and the data it was given is left alone", () => {
    const given = tiny();
    const reader = createCatalogueReader([given]);
    const held = reader.getCategory("tiny");
    assert.ok(held);
    assert.notEqual(held, given);
    assert.equal(Object.isFrozen(given), false);
    assert.equal(Object.isFrozen(given.groups[0].requirements[0]), false);

    const attempts: (() => void)[] = [
      () => {
        held.published = false;
      },
      () => {
        held.groups[0].requirements[0].text = "Changed.";
      },
      () => {
        held.groups[0].requirements.push({ id: "A9", text: "Added.", baseline: true, size: "S", key: "none" });
      },
      () => {
        held.groups.pop();
      },
      () => {
        if (held.coverage) held.coverage.rows[0].marks[0] = "N";
      },
      () => {
        held.comments.length = 0;
      },
      () => {
        held.products[0].tier = "Changed";
      },
      () => {
        held.notes[0].paragraphs[0] = "Changed.";
      },
      () => {
        (reader.publishedCategories() as ToolCategory[]).pop();
      },
      () => {
        (reader.allCategoriesIncludingUnpublished() as ToolCategory[]).push(given);
      },
    ];
    for (const attempt of attempts) assert.throws(attempt, TypeError);
    assert.deepEqual(held, given, "nothing changed");
    assert.equal(reader.publishedCategories().length, 1);
  });

  test("the generated data is frozen too, so one request cannot change it for the next", () => {
    const all = allCategoriesIncludingUnpublished();
    assert.throws(() => {
      (all as ToolCategory[]).pop();
    }, TypeError);
    for (const category of all) {
      const first = category.groups[0].requirements[0];
      const text = first.text;
      assert.throws(() => {
        first.text = "Changed.";
      }, TypeError);
      assert.throws(() => {
        category.groups[0].requirements.push({ ...first });
      }, TypeError);
      assert.throws(() => {
        category.published = !category.published;
      }, TypeError);
      assert.equal(category.groups[0].requirements[0].text, text);
    }
    assert.deepEqual(all, TOOL_CATEGORIES);
    assert.notEqual(all[0], TOOL_CATEGORIES[0], "the reader holds its own frozen copy");
  });

  test("the module exposes exactly two doors to a category list", () => {
    const source = read("../app/lib/project-builder/tool-catalogue-read.ts");
    const exported = [...source.matchAll(/^export function (\w+)/gm)].map((match) => match[1]);
    const doors = exported.filter((name) => /categor/i.test(name) && name !== "createCatalogueReader");
    assert.deepEqual(doors.sort(), ["allCategoriesIncludingUnpublished", "getCategory", "publishedCategories"]);
    assert.equal(/export\s+(const|let|var)\s/.test(source), false);
    assert.equal(/export\s*\{[^}]*TOOL_CATEGORIES/.test(source), false);
  });
});
